const DICT = { pt, en, es };
const STORAGE_KEY = "app_lang";

const fallback = {
  lang: "pt",
  locale: "pt-BR",
  setLang: () => {},
  t: (key) => DICT.pt[key] ?? key,
  tServer: (message) => message || "",
};

const LanguageContext = createContext(fallback);

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState("pt");

  useEffect(() => {
    try {
      const saved = window.localStorage.getItem(STORAGE_KEY);
      if (saved && DICT[saved]) setLangState(saved);
    } catch {
      /* sem acesso ao armazenamento */
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang === "pt" ? "pt-BR" : lang;
  }, [lang]);

  const value = useMemo(() => {
    const dict = DICT[lang] || DICT.pt;
    const locale = LANGS.find((l) => l.code === lang)?.locale || "pt-BR";
    const setLang = (code) => {
      if (!DICT[code]) return;
      setLangState(code);
      try {
        window.localStorage.setItem(STORAGE_KEY, code);
      } catch {
        /* sem acesso ao armazenamento */
      }
    };
    return {
      lang,
      locale,
      setLang,
      t: (key, vars) => {
        let text = dict[key] ?? DICT.pt[key] ?? key;
        if (vars) {
          for (const [name, replacement] of Object.entries(vars)) {
            text = text.replaceAll(`{${name}}`, String(replacement));
          }
        }
        return text;
      },
      tServer: (message) => (message && dict.srv?.[message]) || message || "",
    };
  }, [lang]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export const useI18n = () => useContext(LanguageContext);